BEGIN;

CREATE INDEX IF NOT EXISTS game_suggestions_user_id_idx
    ON public.game_suggestions (user_id)
    WHERE user_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS game_issue_reports_user_id_idx
    ON public.game_issue_reports (user_id)
    WHERE user_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.moderation_deletion_audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id uuid NOT NULL
        REFERENCES auth.users (id) ON DELETE CASCADE,
    submitted_by_user_id uuid
        REFERENCES auth.users (id) ON DELETE SET NULL,
    item_type text NOT NULL
        CHECK (item_type IN ('suggestion', 'issue_report')),
    item_id text NOT NULL,
    deleted_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.moderation_deletion_audit ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.moderation_deletion_audit
    FROM PUBLIC, anon, authenticated;

CREATE INDEX IF NOT EXISTS moderation_deletion_audit_actor_type_idx
    ON public.moderation_deletion_audit (actor_user_id, item_type);
CREATE INDEX IF NOT EXISTS moderation_deletion_audit_submitter_type_idx
    ON public.moderation_deletion_audit (submitted_by_user_id, item_type)
    WHERE submitted_by_user_id IS NOT NULL;

CREATE OR REPLACE FUNCTION public.audit_game_contribution_deletion()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
    actor_id uuid;
    deleted_record jsonb;
BEGIN
    actor_id := auth.uid();
    deleted_record := to_jsonb(OLD);

    IF actor_id IS NOT NULL THEN
        INSERT INTO public.moderation_deletion_audit (
            actor_user_id,
            submitted_by_user_id,
            item_type,
            item_id
        )
        VALUES (
            actor_id,
            NULLIF(deleted_record->>'user_id', '')::uuid,
            CASE TG_TABLE_NAME
                WHEN 'game_suggestions' THEN 'suggestion'
                WHEN 'game_issue_reports' THEN 'issue_report'
            END,
            deleted_record->>'id'
        );
    END IF;

    RETURN OLD;
END;
$$;

REVOKE ALL ON FUNCTION public.audit_game_contribution_deletion()
    FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS game_suggestions_contribution_deletion_audit
    ON public.game_suggestions;
CREATE TRIGGER game_suggestions_contribution_deletion_audit
    AFTER DELETE ON public.game_suggestions
    FOR EACH ROW
    EXECUTE FUNCTION public.audit_game_contribution_deletion();

DROP TRIGGER IF EXISTS game_issue_reports_contribution_deletion_audit
    ON public.game_issue_reports;
CREATE TRIGGER game_issue_reports_contribution_deletion_audit
    AFTER DELETE ON public.game_issue_reports
    FOR EACH ROW
    EXECUTE FUNCTION public.audit_game_contribution_deletion();

CREATE OR REPLACE FUNCTION public.moderator_approve_game_suggestion(
    target_suggestion_id text
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
    affected_rows integer;
BEGIN
    IF NOT COALESCE(public.can_review_game_suggestions(), false) THEN
        RAISE EXCEPTION 'Moderator access required'
            USING ERRCODE = '42501';
    END IF;

    IF NULLIF(btrim(target_suggestion_id), '') IS NULL THEN
        RAISE EXCEPTION 'A suggestion ID is required'
            USING ERRCODE = '22023';
    END IF;

    IF NOT COALESCE(public.is_admin(), false) AND EXISTS (
        SELECT 1
        FROM public.game_suggestions AS suggestion
        WHERE to_jsonb(suggestion)->>'id' = target_suggestion_id
          AND suggestion.status = 'pending'
          AND suggestion.user_id = auth.uid()
    ) THEN
        RAISE EXCEPTION 'Moderators cannot send their own suggestions to the owner'
            USING ERRCODE = '42501';
    END IF;

    UPDATE public.game_suggestions AS suggestion
    SET status = 'approved'
    WHERE to_jsonb(suggestion)->>'id' = target_suggestion_id
      AND suggestion.status = 'pending';

    GET DIAGNOSTICS affected_rows = ROW_COUNT;
    IF affected_rows = 0 THEN
        RAISE EXCEPTION 'Pending suggestion not found'
            USING ERRCODE = '22023';
    END IF;

    RETURN true;
END;
$$;

CREATE OR REPLACE FUNCTION public.moderator_forward_game_issue_report(
    target_report_id uuid
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
    affected_rows integer;
BEGIN
    IF NOT COALESCE(public.can_review_game_suggestions(), false) THEN
        RAISE EXCEPTION 'Moderator access required'
            USING ERRCODE = '42501';
    END IF;

    IF target_report_id IS NULL THEN
        RAISE EXCEPTION 'A report ID is required'
            USING ERRCODE = '22023';
    END IF;

    IF NOT COALESCE(public.is_admin(), false) AND EXISTS (
        SELECT 1
        FROM public.game_issue_reports AS report
        WHERE report.id = target_report_id
          AND report.status = 'pending'
          AND report.user_id = auth.uid()
    ) THEN
        RAISE EXCEPTION 'Moderators cannot send their own reports to the owner'
            USING ERRCODE = '42501';
    END IF;

    UPDATE public.game_issue_reports
    SET status = 'forwarded'
    WHERE id = target_report_id
      AND status = 'pending';

    GET DIAGNOSTICS affected_rows = ROW_COUNT;
    IF affected_rows = 0 THEN
        RAISE EXCEPTION 'Pending game report not found'
            USING ERRCODE = '22023';
    END IF;

    RETURN true;
END;
$$;

REVOKE ALL ON FUNCTION public.moderator_approve_game_suggestion(text)
    FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.moderator_forward_game_issue_report(uuid)
    FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.moderator_approve_game_suggestion(text)
    TO authenticated;
GRANT EXECUTE ON FUNCTION public.moderator_forward_game_issue_report(uuid)
    TO authenticated;

DROP FUNCTION IF EXISTS public.admin_list_ranked_user_contributions();

CREATE FUNCTION public.admin_list_ranked_user_contributions()
RETURNS TABLE (
    user_id uuid,
    username text,
    rank text,
    suggestions_submitted bigint,
    issues_reported bigint,
    suggestions_deleted bigint,
    issues_deleted bigint
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
BEGIN
    IF auth.uid() IS NULL OR NOT COALESCE(public.is_admin(), false) THEN
        RAISE EXCEPTION 'Owner access required'
            USING ERRCODE = '42501';
    END IF;

    RETURN QUERY
    SELECT
        ranked_user.user_id,
        COALESCE(
            NULLIF(btrim(account.raw_user_meta_data->>'username'), ''),
            NULLIF(btrim(account.raw_user_meta_data->>'display_name'), ''),
            'Player'
        )::text,
        ranked_user.rank,
        (
            SELECT count(*)
            FROM public.game_suggestions AS suggestion
            WHERE suggestion.user_id = ranked_user.user_id
        ) + (
            SELECT count(*)
            FROM public.moderation_deletion_audit AS deletion
            WHERE deletion.item_type = 'suggestion'
              AND deletion.submitted_by_user_id = ranked_user.user_id
        ),
        (
            SELECT count(*)
            FROM public.game_issue_reports AS report
            WHERE report.user_id = ranked_user.user_id
        ) + (
            SELECT count(*)
            FROM public.moderation_deletion_audit AS deletion
            WHERE deletion.item_type = 'issue_report'
              AND deletion.submitted_by_user_id = ranked_user.user_id
        ),
        (
            SELECT count(*)
            FROM public.moderation_deletion_audit AS deletion
            WHERE deletion.item_type = 'suggestion'
              AND deletion.actor_user_id = ranked_user.user_id
        ),
        (
            SELECT count(*)
            FROM public.moderation_deletion_audit AS deletion
            WHERE deletion.item_type = 'issue_report'
              AND deletion.actor_user_id = ranked_user.user_id
        )
    FROM public.user_ranks AS ranked_user
    JOIN auth.users AS account
        ON account.id = ranked_user.user_id
    ORDER BY
        ranked_user.rank,
        lower(COALESCE(
            NULLIF(btrim(account.raw_user_meta_data->>'username'), ''),
            NULLIF(btrim(account.raw_user_meta_data->>'display_name'), ''),
            'Player'
        )),
        ranked_user.user_id;
END;
$$;

REVOKE ALL ON FUNCTION public.admin_list_ranked_user_contributions()
    FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_list_ranked_user_contributions()
    TO authenticated;

COMMIT;
